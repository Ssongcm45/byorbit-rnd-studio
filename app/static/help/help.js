/** (?) 단추 HTML 문자열. 모듈 템플릿 안에 바로 넣을 때 쓴다(초기화 뒤 눌림이 붙는다). */
export function helpButton(id, {label = false} = {}) {
  const h = HELP[id]; if (!h) return '';
  return `<span data-help-chips="${esc(id)}"${label ? '' : ' data-help-bare'}></span>`;
}

function makeBtn(id, label) {
  const h = HELP[id]; if (!h) return null;
  const b = document.createElement('button');
  b.type = 'button';
  b.className = label ? 'hq hq-chip' : 'hq';
  b.dataset.hid = id;
  b.setAttribute('aria-label', `도움말: ${h.title}`);
  b.setAttribute('aria-expanded', 'false');
  b.setAttribute('aria-controls', POP_ID);
  b.setAttribute('aria-haspopup', 'dialog');
  b.innerHTML = Q_ICON + (label ? `<span class="hq-t">${esc(h.title)}</span>` : '');
  wire(b);
  return b;
}

/** el 안(기본) 또는 뒤(pos:'after')에 (?) 단추를 한 번만 붙인다. 붙인 단추를 돌려준다. */
export function attachHelp(el, id, {pos = el?.dataset?.helpPos || 'inside'} = {}) {
  if (!el || !HELP[id]) return null;
  if (pos === 'after') {
    const n = el.nextElementSibling;
    if (n && n.dataset.hid === id) return n;
    const b = makeBtn(id); el.after(b); return b;
  }
  const have = [...el.children].find(c => c.dataset && c.dataset.hid === id);
  if (have) return have;
  const b = makeBtn(id); el.append(b); return b;
}

function ensureChips(box) {
  const ids = box.dataset.helpChips.split(',').map(s => s.trim()).filter(Boolean);
  const bare = box.hasAttribute('data-help-bare');
  const have = [...box.children].map(c => c.dataset.hid).join(',');
  if (have === ids.filter(i => HELP[i]).join(',')) return;
  box.textContent = '';
  for (const i of ids) { const b = makeBtn(i, !bare); if (b) box.append(b) }
}

function scan() {
  for (const el of document.querySelectorAll('[data-help]')) attachHelp(el, el.dataset.help);
  for (const el of document.querySelectorAll('[data-help-chips]')) ensureChips(el);
  if (CUR && !CUR.btn.isConnected) close(false);
}

